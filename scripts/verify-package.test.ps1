param([Parameter(Mandatory)][string]$PackagePath)
$ErrorActionPreference = 'Stop'
$source = (Resolve-Path -LiteralPath $PackagePath).Path
$scratch = Join-Path ([IO.Path]::GetTempPath()) ('hotspot-package-check-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $scratch | Out-Null
try {
    foreach ($case in @('missing-dll', 'wrong-id', 'wrong-dependency', 'raw-source', 'missing-chunk')) {
        $copy = Join-Path $scratch "$case.nupkg"
        Copy-Item -LiteralPath $source -Destination $copy
        $zip = [IO.Compression.ZipFile]::Open($copy, [IO.Compression.ZipArchiveMode]::Update)
        try {
            switch ($case) {
                'missing-dll' { $zip.GetEntry('lib/net10.0/ImageHotspot.dll').Delete() }
                'missing-chunk' { ($zip.Entries | Where-Object { $_.FullName -like 'staticwebassets/App_Plugins/ImageHotspot/imagehotspot.element-*.js' } | Select-Object -First 1).Delete() }
                'raw-source' { $null = $zip.CreateEntry('Client/src/editor.ts') }
                default {
                    $entry = $zip.Entries | Where-Object { $_.FullName -like '*.nuspec' } | Select-Object -First 1
                    $reader = [IO.StreamReader]::new($entry.Open())
                    try { $xml = $reader.ReadToEnd() } finally { $reader.Dispose() }
                    $name = $entry.FullName
                    $entry.Delete()
                    if ($case -eq 'wrong-id') { $xml = $xml.Replace('<id>Umbraco.Community.ImageHotspot</id>', '<id>Other.Package</id>') }
                    else { $xml = $xml.Replace('19.0.0)', '20.0.0)') }
                    $writer = [IO.StreamWriter]::new($zip.CreateEntry($name).Open())
                    try { $writer.Write($xml) } finally { $writer.Dispose() }
                }
            }
        } finally { $zip.Dispose() }
        $rejected = $false
        try { & "$PSScriptRoot/verify-package.ps1" -PackagePath $copy } catch { $rejected = $true }
        if (-not $rejected) { throw "Package verifier accepted $case" }
        Write-Host "Rejected $case as expected."
    }
} finally {
    # Only files generated by this test are removed, without recursive deletion.
    Get-ChildItem -LiteralPath $scratch -File | Remove-Item
    Remove-Item -LiteralPath $scratch
}
